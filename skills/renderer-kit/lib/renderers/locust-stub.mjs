// locust-stub.mjs — a TRIVIAL non-k6 renderer that proves the Renderer interface
// is buildable in parallel (ISI-5655 acceptance: "a trivial non-k6 renderer stub
// compiles against the interface and returns a capability report").
//
// It is deliberately the hardest capability case: Locust is user/closed-native, so
// the OPEN arrival model (G-O1) is the headline approximation the agent must warn a
// human about at VALIDATE. This stub is NOT a production Locust renderer (that is
// ISI-5657) — it emits a readable locustfile skeleton and, crucially, a HONEST
// capability report. It exercises the §4 v1.1 accessors (G-R1/G-P1) so the real
// Locust renderer can be dropped in against the same interface.

import { defineRenderer, makeCapabilityReport } from '../renderer.mjs';
import {
  resolveRequest,
  resolveFieldTarget,
  methodHasBody,
  partitionDrivableSteps,
} from '../model-access.mjs';

/** Build the capability report (declared BEFORE rendering — drives VALIDATE warnings). */
function supports(model) {
  const spec = (model && model.spec) || {};
  const unsupported = [];

  // G-O1: open arrival -> Locust is closed-native; needs LoadTestShape + pacing.
  if (spec.arrivalProfile && spec.arrivalProfile.model === 'open') {
    unsupported.push({
      feature: 'arrivalProfile.model=open',
      reason: 'Locust is user/closed-native (concurrent users, not an arrival rate)',
      approximation: 'LoadTestShape + per-task pacing to approximate the target iterations/s',
    });
  }

  // G-E1: empirical think-time has no native Locust construct.
  const seenEmpirical = new Set();
  // G-X1: non-http steps are topology/baseline only, not driven.
  const undrivenTypes = new Set();
  // body_html extraction has no native Locust extractor.
  let hasBodyHtml = false;

  for (const j of spec.journeys || []) {
    for (const s of j.steps || []) {
      if (s.thinkTime && s.thinkTime.distribution === 'empirical') seenEmpirical.add(s.id);
      for (const c of s.correlates || []) {
        if (c.extract && c.extract.from === 'body_html') hasBodyHtml = true;
      }
    }
    const { undriven } = partitionDrivableSteps(j);
    for (const s of undriven) undrivenTypes.add(s.callType);
  }

  if (seenEmpirical.size) {
    unsupported.push({
      feature: 'thinkTime.distribution=empirical',
      reason: 'Locust wait_time has no native empirical-sample distribution',
      approximation: 'custom wait_time() sampling from the pre-generated empirical list',
    });
  }
  if (hasBodyHtml) {
    unsupported.push({
      feature: 'correlates.extract.from=body_html',
      reason: 'Locust has no native HTML extractor',
      approximation: 'regex / BeautifulSoup extraction in the task body',
    });
  }
  if (undrivenTypes.size) {
    unsupported.push({
      feature: `callType in {${[...undrivenTypes].sort().join(',')}}`,
      reason: 'renderers drive edge HTTP entrypoints only; grpc/db/mq/cache steps are topology/baseline',
      approximation: 'non-http steps are omitted from the locustfile (driven indirectly via the HTTP edge)',
    });
  }

  return makeCapabilityReport(unsupported);
}

/** A readable, DETERMINISTIC locustfile skeleton. No network, no randomness. */
function render(model, _opts = {}) {
  const spec = (model && model.spec) || {};
  const report = supports(model);
  const warnings = report.unsupported.map(
    (u) => `locust: ${u.feature} — ${u.reason}${u.approximation ? ` (approx: ${u.approximation})` : ''}`
  );

  const name = (model && model.metadata && model.metadata.name) || 'workload';
  const lines = [];
  lines.push('# AUTO-GENERATED by renderer-kit locust-stub (ISI-5655). Skeleton only.');
  lines.push(`# Source model: ${name} rev ${(model && model.status && model.status.revision) ?? '?'}`);
  if (report.unsupported.length) {
    lines.push('#');
    lines.push('# CAPABILITY REPORT (approximations applied — confirm at VALIDATE):');
    for (const u of report.unsupported) {
      lines.push(`#   - ${u.feature}: ${u.reason}${u.approximation ? ` -> ${u.approximation}` : ''}`);
    }
  }
  lines.push('');
  lines.push('from locust import HttpUser, task, between');
  lines.push('');
  lines.push(`class ${toClassName(name)}(HttpUser):`);
  lines.push('    wait_time = between(1, 2)  # TODO: honor steps[].thinkTime per task');
  lines.push('');

  for (const j of spec.journeys || []) {
    const weight = Math.max(1, Math.round((j.weight || 0) * 100));
    lines.push(`    @task(${weight})  # journey weight ${j.weight}`);
    lines.push(`    def ${toMethodName(j.id)}(self):`);
    const { driven } = partitionDrivableSteps(j);
    if (!driven.length) {
      lines.push('        pass  # no drivable HTTP edge steps');
    }
    for (const s of driven) {
      const req = resolveRequest(s);
      const verb = req.method.toLowerCase();
      const body = methodHasBody(req.method);
      const note = payloadNote(spec, req.bodyPayloadRef);
      const comment = `  # step ${s.id}${note ? `; payload ${req.bodyPayloadRef} [${note}]` : ''}`;
      if (body) {
        lines.push(`        self.client.${verb}(${pyStr(req.pathTemplate)}, json={})${comment}`);
      } else {
        lines.push(`        self.client.${verb}(${pyStr(req.pathTemplate)})${comment}`);
      }
    }
    lines.push('');
  }

  const content = lines.join('\n');
  return {
    files: [{ path: `locust/${name}.py`, content }],
    warnings,
  };
}

/** Summarize a payload pool's G-P1 field targets as an inline comment hint. */
function payloadNote(spec, payloadRef) {
  if (!payloadRef) return '';
  const pool = spec.payloads && spec.payloads[payloadRef];
  if (!pool || !Array.isArray(pool.fields)) return '';
  return pool.fields
    .map((f) => {
      const t = resolveFieldTarget(f);
      return `${f.name}->${t.into}:${t.as}`;
    })
    .join(', ');
}

function toClassName(s) {
  return String(s)
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('') + 'User';
}
function toMethodName(s) {
  const safe = String(s).replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(safe) ? `j_${safe}` : safe;
}
function pyStr(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

export const locustStub = defineRenderer({
  name: 'locust',
  targetTool: 'Locust (stub — ISI-5657 will replace)',
  schemaRange: '>=1.0 <2.0',
  supports,
  render,
});
