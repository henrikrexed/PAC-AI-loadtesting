// codegen.mjs — model -> k6 script generation (§3.3). Emits ONE k6 script with
// one scenario + one exec function per journey, wiring: G3 executors (arrival),
// G2 correlation chain (correlate), G4 cache-avoidance pools (payloads), and
// synthetic=true baggage + OTel propagation (baggage).

import { buildScenario } from './arrival.mjs';
import {
  parseOperation,
  methodHasBody,
  renderCorrelations,
  renderUrl,
  renderBody,
  renderHeaderInjections,
} from './correlate.mjs';

const K6_METHOD = { GET: 'get', POST: 'post', PUT: 'put', PATCH: 'patch', DELETE: 'del', HEAD: 'head', OPTIONS: 'options' };
function k6Method(method) {
  return K6_METHOD[method] || 'request';
}

function fnName(id) {
  const safe = String(id).replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(safe) ? `j_${safe}` : safe;
}

function jsString(s) {
  return JSON.stringify(String(s));
}

/** Render one journey step as a k6 `group(...)` block + optional think-time. */
function renderStep(step, poolKinds) {
  const { method, path } = parseOperation(step.operation);
  const { lines: corrLines, injections } = renderCorrelations(step);

  let poolKeyExpr = null;
  let payloadRecordExpr = null;
  if (step.payloadRef) {
    const kind = poolKinds[step.payloadRef];
    const ref = `POOL_${fnName(step.payloadRef)}`;
    if (kind === 'cache-key') poolKeyExpr = `pickKey(${ref}, Math.random())`;
    else if (kind === 'record') payloadRecordExpr = `pickRecord(${ref}, Math.random())`;
  }

  const hasBody = methodHasBody(method);
  const url = renderUrl('BASE', path, injections, hasBody ? null : poolKeyExpr);
  const bodyExpr = hasBody ? renderBody(payloadRecordExpr, injections) : null;
  const headerInj = renderHeaderInjections(injections);
  const extraHeaders = hasBody
    ? mergeObjExpr(headerInj, `{ 'Content-Type': 'application/json' }`)
    : headerInj;
  const paramsExpr = `syntheticParams(${extraHeaders}, { step: ${jsString(step.id)} })`;

  const lines = [];
  lines.push(`    group(${jsString(step.id)}, function () {`);
  for (const l of corrLines) lines.push(l);
  lines.push(`      const url = ${url};`);
  if (hasBody) {
    lines.push(`      const body = JSON.stringify(${bodyExpr || '{}'});`);
    lines.push(`      const res = http.${k6Method(method)}(url, body, ${paramsExpr});`);
  } else {
    lines.push(`      const res = http.${k6Method(method)}(url, ${paramsExpr});`);
  }
  lines.push(`      responses[${jsString(step.id)}] = res;`);
  lines.push(
    `      check(res, { ${jsString(`${step.id} status<500`)}: (r) => r.status > 0 && r.status < 500 });`
  );
  lines.push(`    });`);
  if (step.thinkTime) {
    lines.push(`    sleep(thinkSeconds(${JSON.stringify(step.thinkTime)}, Math.random()));`);
  }
  return lines.join('\n');
}

function mergeObjExpr(a, b) {
  if (a === '{}') return b;
  if (b === '{}') return a;
  return `Object.assign({}, ${a}, ${b})`;
}

function renderJourneyFn(journey, poolKinds) {
  const body = (journey.steps || []).map((s) => renderStep(s, poolKinds)).join('\n');
  return [
    `export function ${fnName(journey.id)}() {`,
    `  resetUserSession(BASE);`,
    `  const responses = {};`,
    body,
    `}`,
  ].join('\n');
}

/**
 * Generate the k6 script source + the k6 options object.
 * model       — approved workload model
 * poolKinds   — { <payloadRef>: 'cache-key'|'record' }
 * Returns { source, options, maxRate, warnings }.
 */
export function generateScript(model, poolKinds) {
  const spec = model.spec;
  const warnings = [];
  const scenarios = {};
  const thresholds = { chain_broken: ['count==0'] };
  let maxRate = 0;

  const totalExpected =
    (spec.arrivalProfile.littlesLawCheck &&
      spec.arrivalProfile.littlesLawCheck.expectedConcurrency) ||
    null;

  for (const journey of spec.journeys) {
    const concurrency = totalExpected != null ? totalExpected * journey.weight : undefined;
    const { scenario, maxRate: r, warnings: w } = buildScenario(
      journey.id,
      spec.arrivalProfile,
      journey.weight,
      { concurrency, caps: spec.caps || {} }
    );
    scenario.exec = fnName(journey.id);
    scenarios[journey.id] = scenario;
    maxRate += r;
    warnings.push(...w);
  }

  const options = { scenarios, thresholds };

  const usedPools = new Set();
  for (const j of spec.journeys) for (const s of j.steps || []) if (s.payloadRef) usedPools.add(s.payloadRef);

  const imports = [
    `// AUTO-GENERATED by k6-synthesis. Do not edit by hand.`,
    `// Source model: ${model.metadata.name} rev ${model.status.revision}` +
      ` — approved by ${model.status.approval?.decisionBy} at ${model.status.approval?.decisionAt}`,
    `import http from 'k6/http';`,
    `import { group, sleep, fail, check } from 'k6';`,
    `import { Counter } from 'k6/metrics';`,
    `import { instrumentHTTP } from 'k6/experimental/tracing';`,
    `import { syntheticParams } from './lib/baggage.js';`,
    `import { resetUserSession } from './lib/session.js';`,
    `import { extract } from './lib/chain.js';`,
    `import { thinkSeconds } from './lib/think.js';`,
    `import { pickKey, pickRecord } from './lib/pool.js';`,
  ];
  for (const ref of usedPools) {
    imports.push(`import POOL_${fnName(ref)} from '../payloads/${ref}.json';`);
  }

  const preamble = [
    ``,
    `const BASE = __ENV.BASE_URL || 'http://localhost:8080';`,
    `const chainBroken = new Counter('chain_broken');`,
    ``,
    `// OTel span emission: propagate W3C trace context so backend spans join the`,
    `// trace; every request also carries baggage synthetic=true (syntheticParams),`,
    `// which the collector/SDK baggage processor promotes to the span attribute`,
    `// \`synthetic\` (methodology P4 / §7.7). Verified end-to-end at EXECUTE/G5.`,
    `instrumentHTTP({ propagator: 'w3c' });`,
    ``,
    `export const options = ${JSON.stringify(options, null, 2)};`,
    ``,
  ];

  const fns = spec.journeys.map((j) => renderJourneyFn(j, poolKinds));

  const source = [...imports, ...preamble, ...fns, ``].join('\n');
  return { source, options, maxRate, warnings };
}
